/// Why an evidence write failed.
///
/// The `Display` text is operator-facing and names the ADR clause; [`EvidenceError::code`]
/// is the machine-readable spelling a supervisor stamps onto an ADR-0001 error or a
/// `meta.json` warning.
#[allow(missing_docs, reason = "the #[error] string documents each variant")]
#[derive(Debug, Error)]
pub enum EvidenceError {
    #[error("could not create {path}: {reason}")]
    Io { path: PathBuf, reason: String },

    #[error("could not resolve {path} to a canonical path: {reason}")]
    Canonical { path: PathBuf, reason: String },

    #[error("evidence_path_escape: {path} is not inside the evidence root {root}; a component was a symlink or the path resolved out of the tree (ADR-0002 §6.3)")]
    PathEscape { path: PathBuf, root: PathBuf },

    #[error("evidence_path_exists: {path} is already published, and a published evidence file is immutable (ADR-0002 §6.2); a collision here means a duplicated run_id, which is a bug worth surfacing")]
    PathExists { path: PathBuf },

    #[error("refusing to write a record the contract does not allow: {reason}")]
    Record { reason: String },

    #[error("invalid {field} {value:?}: {reason}")]
    Invalid {
        field: &'static str,
        value: String,
        reason: String,
    },
}

impl EvidenceError {
    /// The machine-readable code.
    ///
    /// `evidence_path_escape` and `evidence_path_exists` are the names ADR-0002 §6.2
    /// and §6.3 give these two failures, so they are spelled with underscores and
    /// stay stable.
    #[must_use]
    pub const fn code(&self) -> &'static str {
        match self {
            Self::Io { .. } | Self::Canonical { .. } => "internal_error",
            Self::PathEscape { .. } => "evidence_path_escape",
            Self::PathExists { .. } => "evidence_path_exists",
            Self::Record { .. } => "record_invalid",
            Self::Invalid { .. } => "validation_failed",
        }
    }
}

fn io_failure(path: &Path, reason: impl std::fmt::Display) -> EvidenceError {
    EvidenceError::Io {
        path: path.to_path_buf(),
        reason: reason.to_string(),
    }
}

/// Resolve `path` to an absolute path with every `.` and `..` gone and every symlink in
/// its existing prefix resolved, **without** requiring the path to exist.
///
/// `canonicalize` needs the file to exist, and the evidence root is resolved long
/// before it is created, so this canonicalizes the deepest existing ancestor and
/// re-applies the rest logically (which is exactly how the kernel would interpret it
/// once created, minus the symlinks that do not exist yet). A `..` is applied to the
/// resolved prefix, so the result never contains one — that is what makes the
/// `starts_with` prefix test in [`checked_child`] meaningful.
fn resolve_path(path: &Path) -> Result<PathBuf, EvidenceError> {
    let absolute =
        std::path::absolute(path).map_err(|reason| io_failure(path, reason.to_string()))?;
    let mut tail: Vec<std::ffi::OsString> = Vec::new();
    let mut walker: &Path = absolute.as_path();
    let resolved_prefix = loop {
        match walker.canonicalize() {
            Ok(real) => break real,
            Err(missing) => match (walker.file_name(), walker.parent()) {
                (Some(name), Some(parent)) => {
                    tail.push(name.to_os_string());
                    walker = parent;
                }
                _ => {
                    return Err(EvidenceError::Canonical {
                        path: path.to_path_buf(),
                        reason: missing.to_string(),
                    });
                }
            },
        }
    };
    let mut out = resolved_prefix;
    for name in tail.iter().rev() {
        match name.to_string_lossy().as_ref() {
            "." => {}
            ".." => {
                out.pop();
            }
            other => out.push(other),
        }
    }
    // `absolute` may still carry a `..` that the loop above never saw because it was
    // inside an existing prefix; `canonicalize` on that prefix already removed it, so
    // the only surviving `..` would have to come from the tail, handled above.
    debug_assert!(
        !out.components()
            .any(|component| component == Component::ParentDir),
        "resolve_path left a `..` in {out:?}"
    );
    Ok(out)
}

/// A directory the writer may publish into: the canonical evidence root, plus the
/// one-shot record that its layout has been laid down.
///
/// Cheap to clone-by-reference and `Sync`: publish is `async` and takes `&self`.
#[derive(Debug)]
pub struct EvidenceRoot {
    /// Canonical (no `..`, symlinks resolved), absolute.
    root: PathBuf,
    /// `true` once [`EvidenceRoot::ensure`] has created the subtrees, the README stub
    /// and the `.gitignore` entries. `AtomicBool` because `ensure` is idempotent and
    /// the `.gitignore` walk is the only part worth not repeating on every publish.
    prepared: AtomicBool,
}

impl EvidenceRoot {
    /// Use `path` as the evidence root, canonicalizing it.
    ///
    /// The path need not exist: [`EvidenceRoot::ensure`] creates it.
    ///
    /// # Errors
    ///
    /// [`EvidenceError::Canonical`] if no ancestor of `path` can be resolved at all
    /// (which in practice means the current working directory has been deleted).
    pub fn new(path: &Path) -> Result<Self, EvidenceError> {
        Ok(Self {
            root: resolve_path(path)?,
            prepared: AtomicBool::new(false),
        })
    }

    /// The precedence ADR-0002 §1.1 pins, with `explicit` already read from
    /// `--evidence-dir` (a caller that resolved it through
    /// [`crate::config::Config`] has already applied the `EVIDENCE_DIR` fallback, and
    /// passes it here as `explicit`).
    ///
    /// # Errors
    ///
    /// As [`EvidenceRoot::new`].
    pub fn resolve(workspace: &Path, explicit: Option<&Path>) -> Result<Self, EvidenceError> {
        let chosen = match explicit {
            Some(path) => path.to_path_buf(),
            None => workspace.join(EVIDENCE_DIR_NAME),
        };
        Self::new(&chosen)
    }

    /// The precedence of [`EvidenceRoot::resolve`], reading `$EVIDENCE_DIR` from the
    /// environment (ADR-0002 §1.1) as the fallback for a missing `explicit`.
    ///
    /// # Errors
    ///
    /// As [`EvidenceRoot::new`].
    pub fn from_env(workspace: &Path, explicit: Option<&Path>) -> Result<Self, EvidenceError> {
        if explicit.is_some() {
            return Self::resolve(workspace, explicit);
        }
        match std::env::var_os("EVIDENCE_DIR") {
            Some(dir) if !dir.is_empty() => Self::new(Path::new(&dir)),
            _ => Self::resolve(workspace, None),
        }
    }

    /// The canonical root.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.root
    }

    /// Create the layout ADR-0002 §1.1/§6.4 requires, idempotently:
    /// the root and `benchmark/`, `coverage/`, `runs/` at mode `0755`, the `README.md`
    /// stub if absent, and the `.gitignore` entries when the root sits in a git
    /// repository.
    ///
    /// `incoming/` is deliberately not created: it is per-run scratch the runner owns
    /// (ADR-0002 §3.1), and an empty one would only confuse a reader.
    ///
    /// # Errors
    ///
    /// [`EvidenceError::Io`] if a directory or the stub cannot be created.
    pub fn ensure(&self) -> Result<(), EvidenceError> {
        for directory in [
            self.root.clone(),
            self.root.join(Kind::Benchmark.as_str()),
            self.root.join(Kind::Coverage.as_str()),
            self.root.join("runs"),
        ] {
            create_dir_mode(&directory)?;
        }
        write_if_absent(&self.root.join("README.md"), README_STUB.as_bytes())?;
        if !self.prepared.load(Ordering::Acquire) {
            match update_gitignore(&self.root) {
                Ok(outcome) => {
                    self.prepared.store(true, Ordering::Release);
                    tracing::debug!(?outcome, root = %self.root.display(), "evidence gitignore checked");
                }
                // A `.gitignore` we cannot write is ADR-0002 §6.4's "skipped silently"
                // case, but "silently" means "not fatal", not "not worth a log line".
                Err(reason) => tracing::warn!(
                    root = %self.root.display(),
                    %reason,
                    "could not update .gitignore for the evidence root; continuing"
                ),
            }
        }
        Ok(())
    }

    /// `.evidence/<kind>/<full-sha>`, verified to be inside the root and to not be
    /// reached through a symlink.
    ///
    /// # Errors
    ///
    /// [`EvidenceError::PathEscape`] on either failure.
    pub fn commit_dir(&self, kind: Kind, commit: &Commit) -> Result<PathBuf, EvidenceError> {
        self.checked_child(&Path::new(kind.as_str()).join(commit.as_str()))
    }

    /// `.evidence/<kind>/<full-sha>/<run_id>.jsonl`.
    ///
    /// # Errors
    ///
    /// [`EvidenceError::PathEscape`] if the directory does not exist or is a symlink, or
    /// the resolved path is outside the root.
    pub fn record_path(
        &self,
        kind: Kind,
        commit: &Commit,
        run_id: &RunId,
    ) -> Result<PathBuf, EvidenceError> {
        let dir = self.commit_dir(kind, commit)?;
        Ok(dir.join(format!("{run_id}.jsonl")))
    }

    /// Join `relative` onto the root and prove the result stayed inside it.
    ///
    /// `relative` is built only from validated components (a `Kind`, a `Commit`), so
    /// this is defence in depth rather than the first line of defence: it is what
    /// catches a *symlink* planted inside the tree — `coverage/<sha>` turned into a link
    /// to `/home/dev`, say — which no amount of input validation would catch, because
    /// the input was a legitimate SHA.
    ///
    /// A path whose tail does not exist yet is allowed: the writer creates directories on
    /// demand, and [`EvidenceRoot::publish`] re-checks after creating. What is never
    /// allowed is a component that *exists* and resolves to something other than the
    /// literal path under the root.
    ///
    /// # Errors
    ///
    /// [`EvidenceError::PathEscape`] if an existing component is a symlink or resolves
    /// outside the root.
    fn checked_child(&self, relative: &Path) -> Result<PathBuf, EvidenceError> {
        for component in relative.components() {
            if matches!(component, Component::ParentDir | Component::CurDir)
                || component.as_os_str().is_empty()
            {
                return Err(EvidenceError::Invalid {
                    field: "path",
                    value: relative.display().to_string(),
                    reason: "an evidence path is built from validated components only".to_owned(),
                });
            }
        }
        let candidate = self.root.join(relative);

        // Walk up to the deepest component that exists; the missing tail is what has not
        // been created yet and has nothing to resolve.
        let mut anchor: &Path = &candidate;
        while anchor.symlink_metadata().is_err() {
            match anchor.parent() {
                Some(parent) if parent.starts_with(&self.root) => anchor = parent,
                _ => break,
            }
        }
        if anchor.symlink_metadata().is_err() {
            // Not one component of the root exists yet: nothing to check against.
            return Ok(candidate);
        }

        let real = anchor
            .canonicalize()
            .map_err(|reason| io_failure(anchor, reason))?;
        // `real != anchor` means a component between the root and `candidate` is a
        // symlink: ADR-0002 §6.3 refuses to write through one rather than following it.
        if real != anchor || !real.starts_with(&self.root) {
            return Err(EvidenceError::PathEscape {
                path: candidate,
                root: self.root.clone(),
            });
        }
        Ok(candidate)
    }

    /// Publish one run's records as `<kind>/<sha>/<run_id>.jsonl`, atomically
    /// (ADR-0002 §6.2), and report what landed where.
    ///
    /// `Ok(None)` means there was nothing to publish: a run that produced no records
    /// writes no file, and `meta.json` is what records the deliberate absence
    /// (ADR-0002 §1.3).
    ///
    /// This is `async` because ADR-0002 §6.3 requires in-process writers to be
    /// serialized by an *async* mutex keyed on the destination path, and this holds it
    /// for the whole write. The filesystem work itself is synchronous — one temp file,
    /// one `rename` — which is the same trade the runner already makes for the run
    /// directories it prepares.
    ///
    /// # Errors
    ///
    /// * [`EvidenceError::Record`] if any line fails the contract check (structurally,
    ///   or against the JSON Schema in a debug build).
    /// * [`EvidenceError::PathExists`] if the destination already exists.
    /// * [`EvidenceError::PathEscape`] if the derived path left the root.
    /// * [`EvidenceError::Io`] for anything the filesystem refused.
    pub async fn publish(&self, run: &RunRecords) -> Result<Option<Published>, EvidenceError> {
        if run.is_empty() {
            return Ok(None);
        }
        // Check everything before touching the filesystem: a refused write should be
        // refused before it can leave a temp file or a directory behind.
        run.check().map_err(|reason| EvidenceError::Record {
            reason: reason.to_string(),
        })?;
        let values = run.to_values().map_err(|reason| EvidenceError::Record {
            reason: reason.to_string(),
        })?;
        if cfg!(debug_assertions) {
            // The full JSON-Schema check in a debug build (the ticket's
            // "a debug_assert/debug build can run the full JSON-Schema check"): the
            // struct check above is what ships, this is what catches a struct check
            // that has quietly drifted from `schema/evidence.schema.json`.
            let validator =
                schema::evidence_validator().map_err(|reason| EvidenceError::Record {
                    reason: reason.to_string(),
                })?;
            for (index, value) in values.iter().enumerate() {
                schema::validate_against(validator, value).map_err(|problem| {
                    EvidenceError::Record {
                        reason: format!(
                            "line {index} fails schema/evidence.schema.json: {problem}"
                        ),
                    }
                })?;
            }
        }
        let bytes = run.to_jsonl().map_err(|reason| EvidenceError::Record {
            reason: reason.to_string(),
        })?;

        let envelope = run.envelope();
        let kind = run.kind();
        self.ensure()?;
        // The commit directory is created here ("on demand", §1.1) and then re-checked:
        // only once it exists can a planted symlink in its path be detected, and §6.3
        // refuses to write through one.
        let directory = self.commit_dir(kind, &envelope.commit)?;
        create_dir_mode(&directory)?;
        let directory = self.commit_dir(kind, &envelope.commit)?;
        let filename = format!("{}.jsonl", envelope.run_id);
        let destination = directory.join(&filename);

        // ADR-0002 §6.3: one writer per canonical destination path, in-process.
        let _writer = guards::lock(&destination).await;
        publish_atomic(&directory, &filename, &destination, &bytes)?;

        Ok(Some(Published {
            kind,
            run_id: envelope.run_id.as_str().to_owned(),
            commit: envelope.commit.as_str().to_owned(),
            path: destination,
            records: run.len(),
            bytes: bytes.len() as u64,
            truncated: run.truncated(),
        }))
    }

    /// The workspace-relative spelling of a published path, i.e. the form
    /// `meta.json`'s `evidence[].path` uses (`.evidence/coverage/<sha>/<run>.jsonl`).
    ///
    /// Returns `None` when the path is not under the root at all (impossible for
    /// anything this writer published) or when the root's own spelling is not
    /// workspace-relative, which is the `--evidence-dir /srv/evidence` case: there is
    /// no honest relative path, and `Published::path` still has the absolute one.
    #[must_use]
    pub fn relative_path(&self, workspace: &Path, path: &Path) -> Option<String> {
        let relative = path.strip_prefix(workspace).ok()?;
        let text = relative.to_string_lossy().replace('\\', "/");
        (!text.starts_with("..")).then_some(text)
    }
}

/// What one successful [`EvidenceRoot::publish`] put on disk — the
/// `meta.json` `evidence[]` entry, minus the fields only the supervisor knows
/// (`malformed`, which the extractor counted).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Published {
    /// Which subtree it landed in.
    pub kind: Kind,
    /// The run that produced it.
    pub run_id: String,
    /// The commit it is filed under.
    pub commit: String,
    /// The absolute path of the published file.
    pub path: PathBuf,
    /// How many lines it holds.
    pub records: usize,
    /// Its size.
    pub bytes: u64,
    /// Whether every line of a truncated run carried `flags:["truncated"]`, which is
    /// `meta.json`'s `evidence[].truncated`.
    pub truncated: bool,
}

/// The body of an atomic publish, with the destination path guard already held.
///
/// Temp file in the destination directory → `fsync` → `rename` → directory `fsync`, in
/// that order, because ADR-0002 §6.2's guarantee is exactly that ordering: `rename` is
/// atomic within a filesystem, and the directory `fsync` is what makes the new name
/// survive a power loss.
fn publish_atomic(
    directory: &Path,
    filename: &str,
    destination: &Path,
    bytes: &[u8],
) -> Result<(), EvidenceError> {
    if destination_exists(destination) {
        return Err(EvidenceError::PathExists {
            path: destination.to_path_buf(),
        });
    }
    // `.<run_id>.jsonl.<random>.tmp` — the name ADR-0002 §1.1 promises readers skip,
    // because it is a dot-file and ends in `.tmp`.
    let temp = directory.join(format!(
        ".{}.{}.tmp",
        filename.trim_end_matches(".jsonl"),
        random_suffix()
    ));
    let wrote = write_temp_then_rename(&temp, destination, bytes);
    if wrote.is_err() {
        // Never leave litter for the next reader to wonder about.
        let _ = std::fs::remove_file(&temp);
    }
    wrote.map_err(|reason| io_failure(destination, reason))
}

fn destination_exists(path: &Path) -> bool {
    // `symlink_metadata`, not `exists`: a dangling link at the destination is as much a
    // collision as a real file, and writing through it is exactly what §6.3 forbids.
    std::fs::symlink_metadata(path).is_ok()
}

fn write_temp_then_rename(temp: &Path, destination: &Path, bytes: &[u8]) -> Result<(), String> {
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(temp)
        .map_err(|reason| reason.to_string())?;
    file.write_all(bytes).map_err(|reason| reason.to_string())?;
    file.flush().map_err(|reason| reason.to_string())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        file.set_permissions(std::fs::Permissions::from_mode(FILE_MODE))
            .map_err(|reason| reason.to_string())?;
    }
    // The content must be on the disk before the name exists, or `rename` can publish
    // an empty file through a crash.
    file.sync_all().map_err(|reason| reason.to_string())?;
    drop(file);

    if destination_exists(destination) {
        return Err(format!(
            "evidence_path_exists: {} appeared while this run was publishing",
            destination.display()
        ));
    }
    std::fs::rename(temp, destination).map_err(|reason| reason.to_string())?;
    sync_dir(temp.parent().unwrap_or_else(|| Path::new("."))).map_err(|reason| {
        format!("rename succeeded but the directory could not be synced: {reason}")
    })
}

/// `fsync` a directory, so a `rename` that succeeded is durable.
///
/// Best-effort by necessity: opening a directory for reading is a POSIX-ism and can
/// fail on a filesystem that dislikes it, and at that point the rename has already
/// happened — failing the publish would report a lost write that actually landed.
fn sync_dir(directory: &Path) -> Result<(), String> {
    #[cfg(unix)]
    {
        match std::fs::File::open(directory) {
            Ok(handle) => handle.sync_all().map_err(|reason| reason.to_string()),
            Err(missing) => Err(missing.to_string()),
        }
    }
    #[cfg(not(unix))]
    {
        let _ = directory;
        Ok(())
    }
}

/// `create_dir_all`, then force the mode ADR-0002 §6.4 pins — `create_dir_all` applies
/// the umask, so a `umask 077` server would otherwise publish an evidence tree no
/// scanner can read.
fn create_dir_mode(path: &Path) -> Result<(), EvidenceError> {
    std::fs::create_dir_all(path).map_err(|reason| io_failure(path, reason))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(DIR_MODE))
            .map_err(|reason| io_failure(path, format!("chmod {DIR_MODE:o}: {reason}")))?;
    }
    Ok(())
}

/// Write `contents` to `path` only if nothing is there, never through a symlink.
fn write_if_absent(path: &Path, contents: &[u8]) -> Result<(), EvidenceError> {
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(mut file) => {
            file.write_all(contents)
                .map_err(|reason| io_failure(path, reason.to_string()))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt as _;
                file.set_permissions(std::fs::Permissions::from_mode(FILE_MODE))
                    .map_err(|reason| io_failure(path, reason))?;
            }
            Ok(())
        }
        // `create_new` fails with AlreadyExists: ADR-0002 §1.4 says never overwrite.
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => Ok(()),
        Err(reason) => Err(io_failure(path, reason.to_string())),
    }
}

