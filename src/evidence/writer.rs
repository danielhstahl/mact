    #[test]
    fn the_evidence_dir_override_wins_over_the_workspace_default() {
        let home = tempfile::tempdir().expect("tempdir");
        let workspace = home.path().join("workspace");
        std::fs::create_dir_all(&workspace).expect("workspace");
        let elsewhere = home.path().join("elsewhere");

        // ADR-0002 §1.1: `--evidence-dir` first, `$EVIDENCE_DIR` second, the workspace
        // default last.
        let explicit = EvidenceRoot::resolve(&workspace, Some(&elsewhere)).expect("explicit");
        assert_eq!(explicit.path(), resolve_path(&elsewhere).unwrap());
        let defaulted = EvidenceRoot::resolve(&workspace, None).expect("default");
        assert_eq!(
            defaulted.path(),
            resolve_path(&workspace.join(".evidence")).unwrap()
        );

        std::env::set_var("EVIDENCE_DIR", &elsewhere);
        let from_env = EvidenceRoot::from_env(&workspace, None).expect("env");
        assert_eq!(from_env.path(), resolve_path(&elsewhere).unwrap());
        std::env::remove_var("EVIDENCE_DIR");
    }

