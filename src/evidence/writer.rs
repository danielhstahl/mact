// `.gitignore` maintenance (ADR-0002 §6.4)
// ---------------------------------------------------------------------------

/// What [`update_gitignore`] decided, so the caller can log it and a test can assert it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GitignoreOutcome {
    /// No `.git` above the evidence root: nothing to do (ADR-0002 §6.4).
    NotARepository,
    /// The patterns were already listed; the file was not touched.
    AlreadyListed,
    /// The file was appended to (created if it did not exist).
    Updated,
    /// `.gitignore` exists but is not a writable regular file; skipped silently.
    NotWritable,
}

/// Append the evidence patterns to the enclosing repository's `.gitignore`.
///
/// The rules ADR-0002 §6.4 pins, and how this honours them:
///
/// * **Only inside a git repository**: the nearest ancestor holding `.git` decides. No
///   repository, no edit — a scratch directory somewhere is not a repo's business.
/// * **Idempotent**: a pattern already listed is not added again. The check is textual
///   (`.evidence/`, `.evidence`, `/.evidence/` all count as listed) rather than
///   `git check-ignore`, so publishing never spawns a subprocess; ADR-0002 §6.4 names
///   `check-ignore` as the equivalent check for a human or CI that wants git's own
///   answer.
/// * **Never reorders or rewrites** existing content: the file is opened in append mode
///   (and created when the repository has no `.gitignore` yet, which is what "appends to
///   an empty list" has to mean), and the only bytes written are a newline (if the last
///   line lacked one), the marker comment (if absent) and the missing patterns.
/// * **Silent when not a repo or not writable**, both of which are ordinary situations
///   rather than failures.
///
/// # Errors
///
/// A one-line reason for an I/O surprise that is neither of the two silent cases.
pub fn update_gitignore(evidence_root: &Path) -> Result<GitignoreOutcome, String> {
    let Some(repo) = git_repository(evidence_root) else {
        return Ok(GitignoreOutcome::NotARepository);
    };
    let gitignore = repo.join(".gitignore");

    let existing = match std::fs::symlink_metadata(&gitignore) {
        Ok(metadata) => {
            if !metadata.is_file() || metadata.permissions().readonly() {
                return Ok(GitignoreOutcome::NotWritable);
            }
            std::fs::read(&gitignore).map_err(|reason| reason.to_string())?
        }
        // No .gitignore at all: creating one is what "appends" means when the list is
        // empty. Its mode is the process default, which is fine for a source file.
        Err(_) => Vec::new(),
    };

    let listed = listed_patterns(&existing);
    let missing: Vec<&str> = GITIGNORE_PATTERNS
        .iter()
        .copied()
        .filter(|pattern| {
            !listed
                .iter()
                .any(|have| have == &normalize_pattern(pattern))
        })
        .collect();
    if missing.is_empty() {
        return Ok(GitignoreOutcome::AlreadyListed);
    }

    let mut append = String::new();
    if !existing.is_empty() && !existing.ends_with(b"\n") {
        append.push('\n');
    }
    if !marker_present(&existing) {
        append.push_str(GITIGNORE_MARKER);
        append.push('\n');
    }
    for pattern in &missing {
        append.push_str(pattern);
        append.push('\n');
    }

    let mut file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&gitignore)
        .map_err(|reason| {
            if reason.kind() == std::io::ErrorKind::PermissionDenied {
                GitignoreOutcome::NotWritable.to_string()
            } else {
                reason.to_string()
            }
        })?;
    file.write_all(append.as_bytes())
        .map_err(|reason| reason.to_string())?;
    file.flush().map_err(|reason| reason.to_string())?;
    Ok(GitignoreOutcome::Updated)
}

impl std::fmt::Display for GitignoreOutcome {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let text = match self {
            Self::NotARepository => "not a git repository",
            Self::AlreadyListed => "already listed",
            Self::Updated => "updated",
            Self::NotWritable => "not writable",
        };
        f.write_str(text)
    }
}

/// The nearest ancestor of `start` that holds a `.git` entry (directory *or* file, so a
/// linked worktree counts).
fn git_repository(start: &Path) -> Option<PathBuf> {
    start
        .ancestors()
        .find(|ancestor| ancestor.join(".git").symlink_metadata().is_ok())
        .map(|ancestor| ancestor.to_path_buf())
}

/// `.gitignore` patterns as data: comments and blanks dropped, surrounding whitespace
/// and a trailing/leading `/` ignored, so `.evidence/`, `/.evidence` and `.evidence`
/// all mean "already listed".
fn listed_patterns(contents: &[u8]) -> Vec<String> {
    String::from_utf8_lossy(contents)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(normalize_pattern)
        .collect()
}

fn normalize_pattern(pattern: &str) -> String {
    pattern.trim().trim_matches('/').to_owned()
}

fn marker_present(contents: &[u8]) -> bool {
    String::from_utf8_lossy(contents)
        .lines()
        .any(|line| line.trim() == GITIGNORE_MARKER)
}

/// The `host` field: this machine's hostname, lowercased (ADR-0002 §2.2).
///
/// Sanitised rather than trusted: `host` is advisory provenance and never a join key, so
/// a weird `/etc/hostname` must not be able to make every write fail. Characters the
/// schema's alphabet does not admit are dropped, and an empty result becomes
/// `localhost`.
#[must_use]
pub fn hostname() -> String {
    let raw = raw_hostname();
    let cleaned: String = raw
        .trim()
        .to_lowercase()
        .chars()
        .filter(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '.' | '_' | '-')
        })
        .collect();
    let cleaned = cleaned.trim_matches(|character| matches!(character, '.' | '_' | '-'));
    if cleaned.is_empty() {
        "localhost".to_owned()
    } else {
        cleaned.to_owned()
    }
}

#[cfg(unix)]
// The one `unsafe` in this module, and the crate root's `deny(unsafe_code)` is left on
// purpose so the note below is the only thing standing between a new `unsafe` and a
// build failure.
#[allow(
    unsafe_code,
    reason = "gethostname(2) has no std equivalent; see the SAFETY note"
)]
fn raw_hostname() -> String {
    let mut buffer = [0_u8; 256];
    // SAFETY: `gethostname` writes at most `buffer.len()` bytes into a buffer of that
    // size and NUL-terminates what fits; the buffer is fully initialised first, and the
    // read below stops at the first NUL and never reads past the 256 bytes we own.
    let status =
        unsafe { libc::gethostname(buffer.as_mut_ptr().cast::<libc::c_char>(), buffer.len()) };
    if status != 0 {
        return std::env::var("HOSTNAME").unwrap_or_else(|_| "localhost".to_owned());
    }
    let end = buffer
        .iter()
        .position(|byte| *byte == 0)
        .unwrap_or(buffer.len());
    String::from_utf8_lossy(&buffer[..end]).into_owned()
}

#[cfg(not(unix))]
fn raw_hostname() -> String {
    std::env::var("HOSTNAME")
        .or_else(|_| std::env::var("COMPUTERNAME"))
        .unwrap_or_else(|_| "localhost".to_owned())
}

/// The entropy in a temp file name: enough that two publishes in the same directory in
/// the same instant cannot collide with each other's temp file.
///
/// The same recipe `crate::runner::hex_random3` uses for `run_id`, not shared with it
/// because that module is `cfg(unix)` and this one is not.
fn random_suffix() -> String {
    let mut bytes = [0_u8; 3];
    let filled = std::fs::File::open("/dev/urandom").is_ok_and(|mut file| {
        use std::io::Read as _;
        file.read_exact(&mut bytes).is_ok()
    });
    if !filled {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|since| since.subsec_nanos())
            .unwrap_or(0);
        let mixed = nanos ^ (std::process::id() << 8);
        bytes = [
            (mixed & 0xff) as u8,
            ((mixed >> 8) & 0xff) as u8,
            ((mixed >> 16) & 0xff) as u8,
        ];
    }
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// ADR-0002 §6.3's in-process single writer: one async mutex per canonical destination
/// path.
///
/// The set of paths is small (one per commit being written to right now), so the table
/// is kept as a `Weak` map and pruned on the way in: a path's mutex lives exactly as
/// long as a writer holds or awaits it, and nothing about the evidence tree remembers
/// a commit that has finished publishing.
///
/// It does not make the writer correct on its own — cross-process serialization is the
/// ADR-0003 workspace lock, and one file per run means two runs never target the same
/// name anyway. What it buys is the invariant ADR-0002 §6.3 states, held locally rather
/// than hoped for: within this process, only one task is between "checked the
/// destination is free" and "renamed into it" for a given path at a time, so
/// [`EvidenceError::PathExists`] always means a real collision rather than a race we
/// lost. The tests in this module prove the observable half of that.
mod guards {
    use std::{
        collections::HashMap,
        path::{Path, PathBuf},
        sync::{Arc, Mutex, Weak},
    };

    use tokio::sync::{Mutex as PathMutex, OwnedMutexGuard};

    static PATHS: Mutex<Option<HashMap<PathBuf, Weak<PathMutex<()>>>>> = Mutex::new(None);

    /// Take the writer guard for `path`, holding it until the returned guard drops.
    pub async fn lock(path: &Path) -> OwnedMutexGuard<()> {
        // The standard-library lock is only ever held long enough to look up or insert
        // one entry, and is never held across an `await`.
        let mutex = {
            let mut table = PATHS
                .lock()
                .unwrap_or_else(|poisoned| poisoned.into_inner());
            let table = table.get_or_insert_with(HashMap::new);
            table.retain(|_, weak| weak.strong_count() > 0);
            match table.get(path).and_then(Weak::upgrade) {
                Some(existing) => existing,
                None => {
                    let fresh = Arc::new(PathMutex::new(()));
                    table.insert(path.to_path_buf(), Arc::downgrade(&fresh));
                    fresh
                }
            }
        };
        mutex.lock_owned().await
    }
}

