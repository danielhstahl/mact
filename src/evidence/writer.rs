/// `chmod` so the operator's umask cannot narrow it.
pub const DIR_MODE: u32 = 0o755;

/// Mode for the files the writer publishes: world-readable, because a scanner may run
/// as another user on a shared build box.
pub const FILE_MODE: u32 = 0o644;

