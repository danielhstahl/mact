//! The evidence writer: where a run's records become files (ADR-0002 §1.1, §6).
//!
//! Three properties matter, and everything else in this file serves them.
//!
//! **Create on demand, at the root that was chosen.** [`EvidenceRoot::resolve`]
//! implements the precedence ADR-0002 §1.1 pins (`--evidence-dir`, then `$EVIDENCE_DIR`,
//! then `<workspace>/.evidence`), canonicalises the result, and creates `.evidence/`,
//! `benchmark/`, `coverage/` and `runs/` with mode `0755` applied by an explicit
//! `chmod` — `create_dir_all` alone would let the umask decide, and a run under
//! `umask 077` would produce an evidence tree no later reader could open.
//!
//! **Publish atomically.** ADR-0002 §6.2's mechanism is followed literally: the whole
//! run's lines are built in memory, written to `.<run_id>.jsonl.<random>.tmp` *in the
//! destination directory*, `fsync`-ed, then `rename`-d into place and the directory
//! `fsync`-ed. A reader therefore sees no file or the whole file; there is no
//! half-written record in any interleaving. Note what this means for the ticket's
//! "one file per `(kind, commit)`, appended": ADR-0002 §6.2 decided *one file per
//! `(kind, commit, run_id)`* and made append-only a property of the directory instead
//! ("`append-only` happens at the directory level"), precisely so that a published file
//! is never opened for writing again. The ADR wins — see its "Considered alternatives"
//! entry — and the writer refuses a second publish onto the same name with
//! [`EvidenceError::PathExists`] rather than merging into it.
//!
//! **Never leave the root.** `commit` and `run_id` arrive from a tool call and become
//! path components. They are validated newtypes (ADR-0002 §1.2, §2.2), so no
//! caller-controlled string ever reaches [`std::path::Path::join`] unvalidated; on top
//! of that, every derived path is canonicalized and required to sit under the canonical
//! root and to be reachable without following a symlink
//! ([`EvidenceError::PathEscape`]).
//!
//! Single-writer discipline is ADR-0002 §6.3: cross-process serialization is the
//! workspace run lock of ADR-0003 (this layer adds no `flock` of its own), and
//! in-process writers are serialized by an async mutex keyed on the canonical
//! destination path — see `guards` (private, same module).

